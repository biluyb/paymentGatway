package com.safaricom.mpesa.repository;

import com.safaricom.mpesa.model.Transaction;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.stereotype.Repository;

import java.util.Optional;

/**
 * TransactionRepository
 *
 * <p>Spring Data JPA repository managing immutable financial audit records.</p>
 *
 * @author Bililign Yibgeta
 * @since 1.0.0
 */
@Repository
public interface TransactionRepository extends JpaRepository<Transaction, Long> {

    /**
     * Resolves a transaction record by its unique external reference.
     *
     * @param transactionReference unique reference generated by M-PESA
     * @return Optional containing the transaction record if found, or empty
     */
    Optional<Transaction> findByTransactionReference(String transactionReference);
}
